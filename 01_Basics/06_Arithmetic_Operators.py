# Taking input from the user
a = int(input("Enter First Number : "))
b = int(input("Enter Second Number : "))

print("\n========== ARITHMETIC OPERATORS ==========")

# Addition
print("Addition (+)              :", a + b)

# Subtraction
print("Subtraction (-)           :", a - b)

# Multiplication
print("Multiplication (*)        :", a * b)

# Division
print("Division (/)              :", a / b)

# Floor Division
print("Floor Division (//)       :", a // b) #Gives the Integer Value of Quotient

# Modulus
print("Modulus (%)               :", a % b)

# Exponentiation
print("Exponentiation (**)       :", a ** b)