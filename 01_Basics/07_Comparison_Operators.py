# Taking input from the user
a = int(input("Enter First Number  : "))
b = int(input("Enter Second Number : "))

print("\n========== COMPARISON OPERATORS ==========")

# Equal To
print(f"{a} == {b} :", a == b)

# Not Equal To
print(f"{a} != {b} :", a != b)

# Greater Than
print(f"{a} > {b} :", a > b)

# Less Than
print(f"{a} < {b} :", a < b)

# Greater Than or Equal To
print(f"{a} >= {b} :", a >= b)

# Less Than or Equal To
print(f"{a} <= {b} :", a <= b)